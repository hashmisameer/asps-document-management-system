/* =============================================================================
   ASPS-DMS  -  0001  Initial schema
   Target: Microsoft SQL Server 2014  (compatibility level 120)

   SQL Server 2014 compatibility notes - deliberately avoided throughout:
     - DROP ... IF EXISTS        (2016+)  -> IF OBJECT_ID(...) IS NOT NULL
     - STRING_AGG               (2017+)  -> FOR XML PATH, or aggregate in Node
     - TRIM                     (2017+)  -> LTRIM(RTRIM(x))
     - JSON functions           (2016+)  -> NVARCHAR(MAX), parsed in Node
     - Temporal tables          (2016+)  -> dbo.AuditLogs is our history
     - AT TIME ZONE             (2016+)  -> all instants stored UTC

   Used, and verified available in 2014:
     - SEQUENCE, OFFSET/FETCH, TRY_CONVERT, IIF   (2012+)
     - Filtered indexes, DATE, DATETIME2          (2008+)

   All instants are UTC via SYSUTCDATETIME(). Calendar values (JoiningDate,
   DueDate) are DATE, so no timezone conversion can ever shift them.
   ============================================================================= */

SET NOCOUNT ON;
GO

/* -----------------------------------------------------------------------------
